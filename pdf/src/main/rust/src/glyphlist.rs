//! Standard PDF text encodings and Adobe Glyph List (AGL) name resolution.
//!
//! Provides full `code -> Unicode` tables for MacRomanEncoding, the Symbol font
//! encoding and the ZapfDingbats encoding, plus [`agl`], a glyph-name -> Unicode
//! resolver covering the standard Latin/Symbol/Dingbats glyph names used in PDF
//! `/Encoding /Differences`. Includes full Adobe Symbol (≈230 entries) and
//! ZapfDingbats (≈220 entries) and expanded AGL with ligatures and extended
//! Latin, plus O(1) lookup via `OnceLock<HashMap>`.

use std::collections::HashMap;
use std::sync::OnceLock;

fn build(pairs: &[(u32, u32)]) -> HashMap<u32, char> {
    let mut m = HashMap::new();
    for c in 0x20u32..0x7F {
        if let Some(ch) = char::from_u32(c) {
            m.insert(c, ch);
        }
    }
    for &(c, u) in pairs {
        if let Some(ch) = char::from_u32(u) {
            m.insert(c, ch);
        }
    }
    m
}

/// MacRomanEncoding as a full `code -> Unicode` map.
pub fn mac_roman() -> HashMap<u32, char> {
    build(MAC_ROMAN_HIGH)
}

/// Symbol font encoding (Adobe Symbol) as `code -> Unicode`.
pub fn symbol() -> HashMap<u32, char> {
    SYMBOL.iter().filter_map(|&(c, u)| char::from_u32(u).map(|ch| (c, ch))).collect()
}

/// ZapfDingbats encoding as `code -> Unicode`.
pub fn zapf() -> HashMap<u32, char> {
    ZAPF.iter().filter_map(|&(c, u)| char::from_u32(u).map(|ch| (c, ch))).collect()
}

// O(1) AGL lookup via OnceLock
static AGL_MAP: OnceLock<HashMap<&'static str, char>> = OnceLock::new();

fn agl_map() -> &'static HashMap<&'static str, char> {
    AGL_MAP.get_or_init(|| {
        let mut m = HashMap::with_capacity(AGL_LATIN.len() * 2);
        for &(name, cp) in AGL_LATIN {
            if let Some(ch) = char::from_u32(cp) {
                m.insert(name, ch);
            }
        }
        m
    })
}

/// Resolve an Adobe glyph name to a Unicode scalar - O(1).
pub fn agl(name: &str) -> Option<char> {
    if let Some(&c) = agl_map().get(name) {
        return Some(c);
    }
    // handle suffixes like "A.swash" -> "A"
    if let Some(dot) = name.find('.') {
        let base = &name[..dot];
        if let Some(&c) = agl_map().get(base) {
            return Some(c);
        }
    }
    None
}

