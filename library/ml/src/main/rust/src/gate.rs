//! Google's always-on music gate — `music_detector.sound_model` subgraph 3, on the CPU.
//!
//! This is the cheap half of Now Playing. It answers "is this music?" once per 10 ms hop
//! from 8,200 int8 parameters, and only when it says yes does the expensive thing happen:
//! [`crate::nets::nnfp`], the 172,576-parameter fingerprinter in `sound_model_2`, which
//! turns ~4.8 s of audio into a 64-value descriptor. The two are different networks with
//! different jobs and are not interchangeable — the gate is streaming and stateful, the
//! fingerprinter is episodic and stateless.
//!
//! # Why this is not on the GPU
//!
//! Everything else in this crate runs on Vulkan, and this deliberately does not. The gate
//! runs at 100 Hz to compute ~8,200 multiply-accumulates per invocation. That is 820
//! kMAC/s — microseconds of CPU. As a Vulkan dispatch it would be 100 submit/fence/readback
//! round trips a second, where the overhead exceeds the arithmetic by orders of magnitude
//! and the GPU never gets to idle, on a workload whose entire purpose is to be cheap enough
//! to leave running. Google ships it on a DSP for the same reason. Vulkan stays for the
//! fingerprinter, which is episodic and 20x the arithmetic.
//!
//! # Provenance
//!
//! The topology, all 28 quantization scales and the classifier's parameters were recovered
//! from the shipped flatbuffer; `detector/ARCHITECTURE.md` section 3 is the write-up and
//! marks each fact verified or inferred. `scripts/ml/gate_reference.py` extracts
//! `gate.bin` from that flatbuffer, re-checks every scale against the document, and is the
//! independent float64 reference this module's tests are pinned to.
//!
//! # What is a guess
//!
//! Two things in the chain are inferences, not recovered values, and both are marked at
//! their definitions: the sigmoid reading of the int16 score ([`probability`]) and the
//! mean smoothing inside [`Latch`]. [`Hysteresis::SHIPPED`] itself *was* decoded from the
//! model and is not a guess — but see its documentation, because a tuned deployment is
//! very unlikely to want Google's numbers unchanged.

use crate::microfrontend::{Config, Frontend, NOW_PLAYING};

/// Mel channels per frame, in and all the way through: the trunk does not ramp.
pub const CHANNELS: usize = 32;

/// Taps in each depthwise convolution, and so the depth of each circular buffer.
const TAPS: usize = 4;

/// Depthwise-separable blocks in the trunk.
const BLOCKS: usize = 6;

/// The last circular buffer is five deep rather than four, and feeds the dense head.
const HEAD_FRAMES: usize = 5;

/// Width of the hidden dense layer.
const HIDDEN: usize = 8;

/// 10 ms at 16 kHz. One score comes out per hop.
pub const HOP_SAMPLES: usize = NOW_PLAYING.hop_samples;

/// Frames of context behind a fully-warmed score: `1 + 6*(4-1) + (5-1)`.
///
/// 23 frames is 230 ms, plus the front end's 25 ms analysis window. Every circular buffer
/// starts at raw zero, so scores before this are computed from padding and are not
/// reported.
pub const RECEPTIVE_FIELD_FRAMES: usize = 1 + BLOCKS * (TAPS - 1) + (HEAD_FRAMES - 1);

/// Log-mel arrives as int16 in `ln * 1600` units — `FilterBankLog`'s `output_scale`.
const INPUT_SCALE: f64 = 0.000625;

/// The int8 the trunk actually consumes. `1/17`, so the front end's ceiling of `ln = 15`
/// lands exactly on 127 and silence lands exactly on -128.
const FEATURE_SCALE: f64 = 0.05882353;
const FEATURE_ZERO: i32 = -128;

/// The int16 the classifier reads: a symmetric `[-10, +10]` logit across the uint16 span.
/// `0.0006103702 * 32767 == 20.0` exactly and the zero point is the midpoint.
const SCORE_SCALE: f64 = 0.0006103702;
const SCORE_ZERO: i32 = 16383;

// Generated by scripts/ml/gate_reference.py. Do not edit by hand.

/// Weight scales, in blob order: depthwise and pointwise for each of the six blocks, then
/// the two dense layers.
#[rustfmt::skip]
const WEIGHT_SCALES: [f64; 14] = [
    0.0033009361941367388, 0.02450198121368885, 0.0029660481959581375, 0.04827023297548294,
    0.0024130232632160187, 0.0426376573741436, 0.0016810939414426684, 0.039270784705877304,
    0.0020342874340713024, 0.039758771657943726, 0.001741022919304669, 0.030668029561638832,
    0.018677351996302605, 0.009629064239561558,
];

/// Output scale and zero point of each of those fourteen layers.
#[rustfmt::skip]
const OUTPUT_QUANT: [(f64, i32); 14] = [
    (0.09264124184846878, 0),   (0.04185086488723755, 0),
    (0.005776040256023407, 0),  (0.03140326589345932, -1),
    (0.009019619785249233, 0),  (0.02960633672773838, 0),
    (0.007337798364460468, 0),  (0.024098465219140053, 0),
    (0.011312435381114483, 0),  (0.02513219602406025, 0),
    (0.010261553339660168, 0),  (0.020659184083342552, 0),
    (0.02616318315267563, -1),  (0.0784313753247261, -1),
];

/// The 8,200 int8 weights and 393 int32 biases, in execution order.
///
/// Embedded rather than loaded from a `.maml` asset like every other net here. The `.maml`
/// path exists to get tensors into a `VkBuffer`; this network never touches a device, and
/// 9,772 bytes is smaller than the plumbing would be. Regenerate with
/// `python scripts/ml/gate_reference.py <music_detector.sound_model>`.
const BLOB: &[u8] = include_bytes!("gate.bin");

struct Cursor<'a> {
    data: &'a [u8],
    at: usize,
}

impl<'a> Cursor<'a> {
    fn weights(&mut self, count: usize) -> Vec<i32> {
        let out = self.data[self.at..self.at + count]
            .iter()
            .map(|&b| b as i8 as i32)
            .collect();
        self.at += count;
        out
    }

    fn biases(&mut self, count: usize) -> Vec<i32> {
        let out = self.data[self.at..self.at + count * 4]
            .chunks_exact(4)
            .map(|c| i32::from_le_bytes([c[0], c[1], c[2], c[3]]))
            .collect();
        self.at += count * 4;
        out
    }
}

/// One depthwise-separable block: a 4-tap per-channel filter over time, then a 32x32 mix.
struct Block {
    depthwise: Vec<i32>,
    depthwise_bias: Vec<i32>,
    pointwise: Vec<i32>,
    pointwise_bias: Vec<i32>,
}

struct Parameters {
    blocks: Vec<Block>,
    dense: Vec<i32>,
    dense_bias: Vec<i32>,
    logit: Vec<i32>,
    logit_bias: Vec<i32>,
}

impl Parameters {
    fn load() -> Parameters {
        let mut c = Cursor { data: BLOB, at: 0 };
        let blocks = (0..BLOCKS)
            .map(|_| Block {
                depthwise: c.weights(TAPS * CHANNELS),
                depthwise_bias: c.biases(CHANNELS),
                pointwise: c.weights(CHANNELS * CHANNELS),
                pointwise_bias: c.biases(CHANNELS),
            })
            .collect();
        Parameters {
            blocks,
            dense: c.weights(HIDDEN * HEAD_FRAMES * CHANNELS),
            dense_bias: c.biases(HIDDEN),
            logit: c.weights(HIDDEN),
            logit_bias: c.biases(1),
        }
    }
}

/// TFLite's affine requantization: an exact integer accumulator scaled into int8.
///
/// Rounds halves away from zero, matching `MultiplyByQuantizedMultiplier`. `relu` folds
/// the fused activation in by clamping at the zero point, which is where real zero sits.
fn requantize(accumulator: i32, multiplier: f64, zero: i32, relu: bool) -> i32 {
    let scaled = accumulator as f64 * multiplier;
    let q = scaled.round() as i32 + zero;
    q.clamp(if relu { zero } else { -128 }, 127)
}

/// Quantize one natural-log mel value the way `FilterBankLog` does.
fn quantize_logmel(value: f32) -> i32 {
    let q = (value as f64 / INPUT_SCALE).round();
    q.clamp(-32768.0, 32767.0) as i32
}

/// The int16 score as a probability.
///
/// **Inferred, not recovered.** The graph emits a logit and the classifier's thresholds
/// are floats in `0..1`, so a sigmoid has to sit between them, but the operator itself is
/// opaque and the step is not in the graph. The only competing reading is a plain linear
/// `q / 32767`, which would make the tensor's scale and zero point meaningless. See
/// `detector/ARCHITECTURE.md` section 3.4 — confirming this against the real detector is
/// the single highest-value experiment available.
pub fn probability(score: i16) -> f32 {
    let logit = (score as i32 - SCORE_ZERO) as f64 * SCORE_SCALE;
    (1.0 / (1.0 + (-logit).exp())) as f32
}

/// The classifier trunk: log-mel frames in, one int16 score per frame out.
///
/// Stateful. Six four-deep circular buffers and one five-deep buffer carry 230 ms of
/// context between calls, so a caller starting a fresh session must [`Gate::reset`] or it
/// inherits the previous session's audio.
pub struct Gate {
    parameters: Parameters,
    /// Buffer `n` holds block `n`'s input; the last is the dense head's five frames.
    buffers: Vec<Vec<i32>>,
    frames: usize,
    scratch: Vec<i32>,
}

impl Default for Gate {
    fn default() -> Gate {
        Gate::new()
    }
}

impl Gate {
    pub fn new() -> Gate {
        let mut gate = Gate {
            parameters: Parameters::load(),
            buffers: Vec::new(),
            frames: 0,
            scratch: vec![0; CHANNELS],
        };
        gate.reset();
        gate
    }

    /// Clear the circular buffers and the warm-up count.
    pub fn reset(&mut self) {
        // Raw zero, not the zero point: TFLM memsets a CIRCULAR_BUFFER's variable tensor,
        // so a cold buffer decodes to `-zp * scale` rather than to silence. That is what
        // the shipped model does, and the resulting transient is why the first
        // `RECEPTIVE_FIELD_FRAMES` scores are withheld rather than reported.
        self.buffers = (0..BLOCKS)
            .map(|_| vec![0i32; TAPS * CHANNELS])
            .chain(std::iter::once(vec![0i32; HEAD_FRAMES * CHANNELS]))
            .collect();
        self.frames = 0;
    }

    /// Frames pushed since the last [`Gate::reset`].
    pub fn frames(&self) -> usize {
        self.frames
    }

    /// Feed one frame of [`CHANNELS`] natural-log mel values.
    ///
    /// Returns the int16 score, or `None` until [`RECEPTIVE_FIELD_FRAMES`] frames have
    /// arrived and the context is real audio rather than the cold buffers' padding.
    pub fn push(&mut self, logmel: &[f32]) -> Option<i16> {
        debug_assert_eq!(logmel.len(), CHANNELS);
        let mut frame = [0i16; CHANNELS];
        for (out, &value) in frame.iter_mut().zip(logmel) {
            *out = quantize_logmel(value) as i16;
        }
        let score = self.evaluate(&frame);
        self.frames += 1;
        (self.frames >= RECEPTIVE_FIELD_FRAMES).then_some(score)
    }

    /// The forward pass, with no warm-up gate. Takes the int16 the DSP front end emits.
    fn evaluate(&mut self, logmel: &[i16; CHANNELS]) -> i16 {
        for (slot, &value) in self.scratch.iter_mut().zip(logmel) {
            let q = (value as f64 * INPUT_SCALE / FEATURE_SCALE).round() as i32;
            *slot = (q + FEATURE_ZERO).clamp(-128, 127);
        }
        shift_in(&mut self.buffers[0], &self.scratch);

        let (mut in_scale, mut in_zero) = (FEATURE_SCALE, FEATURE_ZERO);
        for index in 0..BLOCKS {
            let block = &self.parameters.blocks[index];
            let (dw_scale, dw_zero) = OUTPUT_QUANT[index * 2];
            let (pw_scale, pw_zero) = OUTPUT_QUANT[index * 2 + 1];

            // 4-tap FIR over time, one filter per channel, no activation.
            let multiplier = in_scale * WEIGHT_SCALES[index * 2] / dw_scale;
            let mut middle = [0i32; CHANNELS];
            for (channel, slot) in middle.iter_mut().enumerate() {
                let mut acc = block.depthwise_bias[channel];
                for tap in 0..TAPS {
                    let x = self.buffers[index][tap * CHANNELS + channel] - in_zero;
                    acc += x * block.depthwise[tap * CHANNELS + channel];
                }
                *slot = requantize(acc, multiplier, dw_zero, false);
            }

            // 1x1 pointwise: a dense 32x32 mix with ReLU.
            let multiplier = dw_scale * WEIGHT_SCALES[index * 2 + 1] / pw_scale;
            for (out, slot) in self.scratch.iter_mut().enumerate() {
                let row = &block.pointwise[out * CHANNELS..(out + 1) * CHANNELS];
                let mut acc = block.pointwise_bias[out];
                for (input, weight) in middle.iter().zip(row) {
                    acc += (input - dw_zero) * weight;
                }
                *slot = requantize(acc, multiplier, pw_zero, true);
            }
            shift_in(&mut self.buffers[index + 1], &self.scratch);
            in_scale = pw_scale;
            in_zero = pw_zero;
        }

        let (dense_scale, dense_zero) = OUTPUT_QUANT[12];
        let (logit_scale, logit_zero) = OUTPUT_QUANT[13];
        let width = HEAD_FRAMES * CHANNELS;
        let head = &self.buffers[BLOCKS];

        let multiplier = in_scale * WEIGHT_SCALES[12] / dense_scale;
        let mut hidden = [0i32; HIDDEN];
        for (unit, slot) in hidden.iter_mut().enumerate() {
            let row = &self.parameters.dense[unit * width..(unit + 1) * width];
            let mut acc = self.parameters.dense_bias[unit];
            for (input, weight) in head.iter().zip(row) {
                acc += (input - in_zero) * weight;
            }
            *slot = requantize(acc, multiplier, dense_zero, true);
        }

        let multiplier = dense_scale * WEIGHT_SCALES[13] / logit_scale;
        let mut acc = self.parameters.logit_bias[0];
        for (input, weight) in hidden.iter().zip(&self.parameters.logit) {
            acc += (input - dense_zero) * weight;
        }
        let logit = requantize(acc, multiplier, logit_zero, false);

        // Re-quantize the int8 logit into the int16 the classifier reads.
        let real = (logit - logit_zero) as f64 * logit_scale;
        let score = (real / SCORE_SCALE).round() as i32 + SCORE_ZERO;
        score.clamp(-32768, 32767) as i16
    }
}

/// Drop the oldest frame and append `frame`, oldest first — TFLM's `CIRCULAR_BUFFER`.
fn shift_in(buffer: &mut [i32], frame: &[i32]) {
    buffer.copy_within(CHANNELS.., 0);
    let tail = buffer.len() - CHANNELS;
    buffer[tail..].copy_from_slice(frame);
}

/// Parameters of the `SmoothedLatchingClassifier` that ends subgraph 3.
///
/// [`Hysteresis::SHIPPED`] is what Google's model carries. Everything here is a tunable,
/// and holding a phone's microphone open on somebody else's operating point is a decision
/// worth making deliberately: these numbers were chosen against Google's front end, their
/// training distribution and their false-accept budget, none of which are reproduced here.
/// Treat them as a starting point to measure from, not as a target to match.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Hysteresis {
    /// Smoothed probability at or above which the positive condition holds.
    pub positive_threshold: f32,
    /// Smoothed probability below which it stops holding. The gap to
    /// [`Hysteresis::positive_threshold`] is the hysteresis band.
    pub negative_threshold: f32,
    /// Consecutive frames the positive condition must hold before an event fires.
    pub positive_frames_before_event: u32,
    /// Consecutive frames the negative condition must hold before the state drops.
    pub negative_frames_before_event: u32,
    /// Frames after a positive event during which another cannot fire.
    pub positive_event_timeout_frames: u32,
    /// Frames after a negative event during which another cannot fire.
    pub negative_event_timeout_frames: u32,
    /// Frames after a reset during which no event may fire at all.
    pub initial_squelch_frames: u32,
    /// Scores averaged into the smoothed score.
    pub window_frames: usize,
    /// Whether the positive state, once entered, never clears.
    pub positive_state_is_persistent: bool,
    /// Whether entering the positive state emits an event.
    pub generate_positive_events: bool,
    /// Whether leaving it emits one.
    pub generate_negative_events: bool,
}

impl Hysteresis {
    /// The values decoded out of the shipped model's custom-options flexbuffer.
    ///
    /// These are recovered, not invented — `detector/ARCHITECTURE.md` section 3.4 marks
    /// them verified. What could *not* be recovered is `music_detector.descriptor`'s
    /// runtime overrides: that file is a symbol and byte-offset table with no values in
    /// it, and it exists precisely so the DSP host can poke these fields at startup. So
    /// the numbers below are what the model was exported with, and are not necessarily
    /// what the shipped feature runs on.
    ///
    /// A 1-frame negative delay at 100 Hz is very twitchy for an always-on listener, and
    /// a 0.01 hysteresis band is narrow; expect to widen both.
    pub const SHIPPED: Hysteresis = Hysteresis {
        positive_threshold: 0.58,
        negative_threshold: 0.57,
        positive_frames_before_event: 5,
        negative_frames_before_event: 1,
        positive_event_timeout_frames: 1,
        negative_event_timeout_frames: 0,
        initial_squelch_frames: 0,
        window_frames: 5,
        positive_state_is_persistent: false,
        generate_positive_events: true,
        generate_negative_events: false,
    };
}

impl Default for Hysteresis {
    fn default() -> Hysteresis {
        Hysteresis::SHIPPED
    }
}

/// What one frame did to the latching classifier.
#[derive(Clone, Copy, Debug, PartialEq)]
pub struct Verdict {
    /// The mean of the last [`Hysteresis::window_frames`] scores, as a probability.
    pub smoothed: f32,
    /// Whether the positive state is currently held.
    pub active: bool,
    /// Whether this frame entered the positive state and an event fired.
    pub positive_event: bool,
    /// Whether this frame left it and an event fired.
    pub negative_event: bool,
}

/// The `SmoothedLatchingClassifier` state machine.
///
/// The `:nowplaying` app smooths in Kotlin, so this is not on the path a `MusicDetector`
/// takes; it is here because it is part of subgraph 3 and because it is the reference for
/// what Google's own parameters do to a score stream.
pub struct Latch {
    parameters: Hysteresis,
    window: Vec<i16>,
    filled: usize,
    next: usize,
    frames: u32,
    positive_run: u32,
    negative_run: u32,
    since_positive: u32,
    since_negative: u32,
    active: bool,
}

impl Latch {
    pub fn new(parameters: Hysteresis) -> Latch {
        let window = vec![0i16; parameters.window_frames.max(1)];
        let mut latch = Latch {
            parameters,
            window,
            filled: 0,
            next: 0,
            frames: 0,
            positive_run: 0,
            negative_run: 0,
            since_positive: u32::MAX,
            since_negative: u32::MAX,
            active: false,
        };
        latch.reset();
        latch
    }

    pub fn reset(&mut self) {
        self.window.fill(0);
        self.filled = 0;
        self.next = 0;
        self.frames = 0;
        self.positive_run = 0;
        self.negative_run = 0;
        self.since_positive = u32::MAX;
        self.since_negative = u32::MAX;
        self.active = false;
    }

    /// Feed one int16 score and advance the state machine.
    pub fn push(&mut self, score: i16) -> Verdict {
        self.window[self.next] = score;
        self.next = (self.next + 1) % self.window.len();
        self.filled = (self.filled + 1).min(self.window.len());

        // Mean of the window, in the score domain, then through the sigmoid. **Inferred**:
        // the operator's name says "smoothed" and its options give a window length, but
        // whether it means mean, median or max is not in the file. Mean is the usual
        // choice and the only one the option set gives no evidence against.
        let total: i32 = self.window[..self.filled].iter().map(|&v| v as i32).sum();
        let mean = (total as f32 / self.filled as f32).round();
        let smoothed = probability(mean.clamp(-32768.0, 32767.0) as i16);

        self.frames = self.frames.saturating_add(1);
        self.since_positive = self.since_positive.saturating_add(1);
        self.since_negative = self.since_negative.saturating_add(1);

        if smoothed >= self.parameters.positive_threshold {
            self.positive_run += 1;
        } else {
            self.positive_run = 0;
        }
        if smoothed < self.parameters.negative_threshold {
            self.negative_run += 1;
        } else {
            self.negative_run = 0;
        }

        let squelched = self.frames <= self.parameters.initial_squelch_frames;
        let mut positive_event = false;
        let mut negative_event = false;

        if !self.active && self.positive_run >= self.parameters.positive_frames_before_event {
            self.active = true;
            positive_event = self.parameters.generate_positive_events
                && !squelched
                && self.since_positive > self.parameters.positive_event_timeout_frames;
            if positive_event {
                self.since_positive = 0;
            }
        } else if self.active
            && !self.parameters.positive_state_is_persistent
            && self.negative_run >= self.parameters.negative_frames_before_event
        {
            self.active = false;
            negative_event = self.parameters.generate_negative_events
                && !squelched
                && self.since_negative > self.parameters.negative_event_timeout_frames;
            if negative_event {
                self.since_negative = 0;
            }
        }

        Verdict {
            smoothed,
            active: self.active,
            positive_event,
            negative_event,
        }
    }
}

/// The whole gate: 16 kHz PCM in, one music probability per 10 ms hop out.
///
/// This is what the JNI layer holds and what `:nowplaying`'s `MusicDetector` is backed by.
/// It owns the log-mel front end, so a caller hands it raw microphone samples and nothing
/// else. Latching is deliberately *not* applied here — the app smooths and latches in
/// Kotlin, and doing it twice would just make the two disagree.
pub struct MusicGate {
    frontend: Frontend,
    gate: Gate,
    frames: Vec<f32>,
}

impl MusicGate {
    pub fn new() -> Result<MusicGate, String> {
        MusicGate::with_config(NOW_PLAYING)
    }

    pub fn with_config(config: Config) -> Result<MusicGate, String> {
        if config.channels != CHANNELS {
            return Err(format!("{} mel channels, not {CHANNELS}", config.channels));
        }
        Ok(MusicGate {
            frontend: Frontend::new(config)?,
            gate: Gate::new(),
            frames: Vec::with_capacity(CHANNELS * 4),
        })
    }

    /// Discard the front end's partial frame and the trunk's context.
    pub fn reset(&mut self) {
        self.frontend.reset();
        self.gate.reset();
    }

    /// Feed PCM and collect one probability per completed hop, oldest first.
    ///
    /// Hops still inside the warm-up produce nothing, so an entirely valid call can append
    /// nothing at all.
    pub fn push(&mut self, pcm: &[i16], out: &mut Vec<f32>) {
        self.frames.clear();
        let produced = self.frontend.process(pcm, &mut self.frames);
        for frame in 0..produced {
            let logmel = &self.frames[frame * CHANNELS..(frame + 1) * CHANNELS];
            if let Some(score) = self.gate.push(logmel) {
                out.push(probability(score));
            }
        }
    }

    /// The most recent probability from `pcm`, or `None` if no hop completed or the gate
    /// is still warming up.
    pub fn score(&mut self, pcm: &[i16]) -> Option<f32> {
        let mut out = Vec::new();
        self.push(pcm, &mut out);
        out.last().copied()
    }

    /// Samples fed since the last [`MusicGate::reset`] have produced this many frames.
    pub fn frames(&self) -> usize {
        self.gate.frames()
    }
}

